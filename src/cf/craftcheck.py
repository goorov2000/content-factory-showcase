"""Детерминированные проверки РЕМЕСЛА сценария — то, чего не было ни в одной из семи
проверок brief-reviewer.md.

Зачем модуль. Аудит 114 сценариев (2026-08-04, agent-runtime/analysis/) показал: ворота
«одобрение сценариев» связывают подлинность референса и соответствие снапшоту формулы —
и в этом кусаются. Но 8 смертельных дефектов из 12 прошли насквозь, потому что ни одна
проверка не смотрела на САМ ТЕКСТ: хук на 255 знаков в трёхсекундном окне, скрипт из
незаполненных `[плейсхолдеров]`, капшен, обещающий то, что скрипт прямо запретил.

Почему это код, а не ещё один пункт в промпте ревьюера. Норма «текст хука не произносим
за 3с» у системы БЫЛА — ревьюер применил её 03.08 к `seven-white-tees` («155 символов,
~9-10с речи»). В тот же день он одобрил `sales-window` с хуком на 255 знаков в том же
окне. Правило, живущее только как суждение агента, применяется случайно; арифметика —
нет. Всё, что здесь есть, детерминировано и объяснимо одной строкой оператору.

Порог речи. 16 знаков в секунду — ставка самого ревьюера из его вердикта 03.08
(155 знаков ≈ 9-10 секунд). Для русской речи это соответствует ~2.5 слова/с. Пороги
держим ОДИН раз здесь, а не в трёх местах.

Модуль чистый: строки на входе, список дефектов на выходе, никакого Sheets и файлов.
"""
import re

# Ставка речи (знаков в секунду) — из вердикта ревьюера 03.08, см. модульный docstring.
CHARS_PER_SECOND = 16.0

# ДОПУСКИ. Здесь стоит машинный гейт, а не редакторский вкус: он обязан ловить только
# то, что нельзя защитить. Поле hook и сегменты раскадровки содержат не одну речь —
# там же текст плашек (появляется мгновенно, времени не занимает) и ремарки. Поэтому
# буквальный счёт завышает: на корпусе 114 сценариев порог «1.0» флагает 94%, то есть
# гасит конвейер, а не чинит его.
#
# Калибровка — по единственным двум применениям нормы, которые в системе БЫЛИ
# (вердикты brief-reviewer 03.08, они же образцы правильного решения):
#   seven-white-tees — отклонён, 151 знак в окне 3с = 3.1× бюджета;
#   sales-window     — пропущен тем же ревьюером в тот же день, 253 знака = 5.3×.
# Порог 3.0 воспроизводит отклонение и ловит пропуск. Всё, что мягче, остаётся
# суждением ревьюера — машина туда не лезет.
HOOK_TOLERANCE = 3.0

# Для сегментов допуск чуть мягче: там доля плашек и ремарок в кавычках заведомо выше,
# чем в поле hook. 2.5 -> 11% корпуса, и это настоящие провалы (до 18.5 слов/с).
SEGMENT_TOLERANCE = 2.5

_SEGMENT = re.compile(r"(\d+)\s*[-–—]\s*(\d+)\s*(?:с|сек|s)\b")
_QUOTED = re.compile(r"[«\"]([^»\"]+)[»\"]")
_PLACEHOLDER = re.compile(r"\[([^\[\]]{3,60})\]")

# Ремарка вместо реплики в поле hook: v4-промпт требует «использовать хотя бы один
# элемент из hook_structure.elements», а elements рецептов — это ОПИСАНИЯ КАДРА. В 12 из
# 13 брифов v4 в hook попало «0-1с: автор уже в кадре…» вместо фразы, которую слышит
# зритель. Поле читают eval и trace — там обязана лежать реплика.
_STAGE_DIRECTION = re.compile(
    r"^\s*(?:\d+\s*[-–—]\s*\d+\s*(?:с|сек|s)\b"
    r"|Плашка\b|Текстом на экране\b|Первый образ уже\b|Первой фразой\b"
    r"|Архивный снимок\b|В кадре\b|Кадр\b|Съёмка\b|Разговорн\w+ (?:исполнение|GRWM)\b)",
    re.IGNORECASE)

# Ссылки на плейсхолдер, которые НЕ дефект: бриф может честно писать «подставь свой
# бренд» — тогда рядом стоит правило подстановки. Признак правила — глагол-инструкция.
_SUBSTITUTION_RULE = re.compile(
    r"подстав\w+|криэйтор подставляет|заполня\w+ криэйтор|выбира\w+ криэйтор", re.I)


def parse_timing(timing):
    """'0-3s' / '0–3с' / '0-5 сек' -> длительность в секундах (float) или None.

    Рецепты пишут hook_structure.timing свободной строкой, поэтому парсер терпимый:
    нечитаемое окно — не повод отказать в одобрении (fail-open), это забота ревьюера.
    """
    m = _SEGMENT.search(str(timing or ""))
    if not m:
        return None
    start, end = int(m.group(1)), int(m.group(2))
    return float(end - start) if end > start else None


def _spoken_chars(text):
    """Сумма длин реплик в кавычках. Кавычки — единственный машинный признак речи,
    которым корпус пользуется последовательно."""
    return sum(len(q.strip()) for q in _QUOTED.findall(text or ""))


def hook_overrun(hook, timing_seconds):
    """Хук не произносим за отведённое окно -> строка дефекта, иначе None.

    Считаем ВЕСЬ текст поля hook, а не только кавычки: поле по определению содержит то,
    что зритель слышит или читает первым. Кавычки внутри снимаются — они разметка речи,
    а не дополнительные знаки.
    """
    if not hook or not timing_seconds:
        return None
    body = re.sub(r"[«»\"]", "", str(hook)).strip()
    budget = timing_seconds * CHARS_PER_SECOND * HOOK_TOLERANCE
    if len(body) <= budget:
        return None
    seconds = len(body) / CHARS_PER_SECOND
    return (f"хук не произносим за отведённое время: {len(body)} знаков — это "
            f"~{seconds:.0f}с речи при окне {timing_seconds:.0f}с "
            f"(норма {budget:.0f} знаков)")


def hook_is_stage_direction(hook):
    """В поле hook лежит ремарка вместо реплики -> строка дефекта, иначе None."""
    if hook and _STAGE_DIRECTION.match(str(hook).strip()):
        head = str(hook).strip()[:60]
        return (f"поле hook содержит описание кадра, а не фразу зрителя: {head!r}… — "
                f"это поле читают eval и trace, в нём обязана быть реплика")
    return None


def segment_overruns(script, limit=3):
    """Сегменты раскадровки, где реплики не влезают в свои секунды.

    Возврат — список строк дефектов, не длиннее limit (оператору нужен диагноз, а не
    простыня). Сегменты без реплик в кавычках пропускаются: немой монтаж — законный
    формат половины рецептов.
    """
    text = str(script or "")
    marks = list(_SEGMENT.finditer(text))
    out = []
    for i, m in enumerate(marks):
        start, end = int(m.group(1)), int(m.group(2))
        duration = end - start
        if duration <= 0:
            continue          # хвостовой «целевой диапазон» вида «55-360 сек» — не сегмент
        body = text[m.end():marks[i + 1].start() if i + 1 < len(marks) else len(text)]
        spoken = _spoken_chars(body)
        if not spoken:
            continue
        budget = duration * CHARS_PER_SECOND * SEGMENT_TOLERANCE
        if spoken > budget:
            out.append(f"сегмент {start}-{end}с: реплик на {spoken} знаков "
                       f"(~{spoken / CHARS_PER_SECOND:.0f}с речи) при {duration}с в кадре")
        if len(out) >= limit:
            break
    return out


def unfilled_placeholders(*texts):
    """Незакрытые подстановки [БРЕНД]/[цена]/[ИМЯ МОДЕЛИ] -> строка дефекта или None.

    Бриф с ними — не сценарий, а бланк: криэйтор не знает, что произносить. Исключение
    одно: рядом стоит явное правило подстановки («криэйтор подставляет реальные
    значения») — тогда пропуск сознательный и остаётся на ревьюере.
    """
    found, guarded = [], False
    for t in texts:
        s = str(t or "")
        hits = _PLACEHOLDER.findall(s)
        if hits:
            found.extend(hits)
            if _SUBSTITUTION_RULE.search(s):
                guarded = True
    if not found or guarded:
        return None
    uniq = sorted({f"[{h}]" for h in found})
    return (f"незаполненные подстановки ({len(found)} шт.): {', '.join(uniq[:5])}"
            + (" …" if len(uniq) > 5 else "")
            + " — криэйтор не знает, что произносить")


# Запрет в сценарии -> что именно в капшене/CTA его нарушает. Пара «регексп запрета,
# регексп нарушения»: скрипт обещает одно, витрина ролика делает ровно обратное.
_CONTRADICTIONS = (
    (re.compile(r"\b(?:ни|без|нет)\s+(?:одной\s+)?(?:цен|артикул)\w*", re.I),
     re.compile(r"артикул\w*|\b\d[\d\s]{2,}\s*(?:₽|руб)", re.I),
     "скрипт запрещает цены и артикулы, а капшен их даёт"),
    (re.compile(r"(?:дат|адрес)\w*[^.]{0,40}(?:нет|не\s+назыв|не\s+указыв)", re.I),
     re.compile(r"\bв\s+эту\s+(?:субботу|пятницу|среду)\b|\bвремя,?\s+место\b", re.I),
     "скрипт запрещает даты и адреса, а капшен их объявляет"),
    (re.compile(r"(?:это\s+)?ПЕРВЫЙ\s+эпизод|эпизод\s*1\b", re.I),
     re.compile(r"эпизод\s*[2-9]\b", re.I),
     "скрипт заявляет первый эпизод серии, а капшен — последующий"),
    (re.compile(r"\bбез\s+(?:ссыл|«?ссылк)|ссылк\w*[^.]{0,30}\bнет", re.I),
     re.compile(r"ссылка\s+в\s+(?:шапк|профил|био)", re.I),
     "скрипт запрещает ссылку в профиле, а CTA её ставит"),
)


# Отрицание перед совпадением: «без ссылок, артикулов и промокодов» — это ПОВТОР
# запрета, а не его нарушение. Без этой поправки проверка ловила ровно те брифы, что
# аккуратнее всех перечисляют свои запреты (numeric-criteria, slim-suit) — то есть
# наказывала за дисциплину.
# Границы слова обязательны (ревью 14.09.2026): без них «сНИмаем», «оНИ», «интерНЕТ»,
# «БЕЗопасная» читались как отрицание, и нарушение рядом молча прощалось.
_NEGATION_BEFORE = re.compile(
    r"(?:\b(?:без|ни|нет)\b|\bникаки\w*|\bне\s+ставим\b|\bне\s+даём\b|\bзапрещ\w*)"
    r"[^.!?;]{0,80}$", re.IGNORECASE)


def _violates(pattern, text):
    """Совпадение, перед которым НЕТ отрицания в той же фразе."""
    return any(not _NEGATION_BEFORE.search(text[:m.start()])
               for m in pattern.finditer(text))


def self_contradiction(script, visual, caption, cta):
    """Скрипт/визуал запрещают то, что капшен или CTA делают -> строка дефекта.

    Такой бриф неисполним: снять по нему можно, только нарушив его же правило или
    соврав зрителю. В корпусе таких четыре, все одобрены.
    """
    rules = f"{script or ''}\n{visual or ''}"
    surface = f"{caption or ''}\n{cta or ''}"
    for ban, violation, message in _CONTRADICTIONS:
        if ban.search(rules) and _violates(violation, surface):
            return f"{message} — снять по такому брифу можно только соврав зрителю"
    return None


# --- пересъёмка ------------------------------------------------------------------
#
# `tested_variable` — единственная антидубликатная норма системы (правило 3
# brief-generator.md: «внутри формулы ротируй tested_variable — брифы одной формулы не
# должны отличаться только словами»). Она не в схеме брифа, не в семи проверках
# ревьюера и не читается воротами: держится на честном слове модели. Модель его
# нарушает — `seven-pairs-mixed` пересобран из трёх более ранних брифов той же формулы
# (7 из 7 цветовых пар), `pairing-close` — брифа от 26.07 плюс один блок с тем же
# хуком дословно. Оба авто-одобрены.
#
# Меряем двумя способами, потому что пересъёмка бывает двух видов:
#   - клон одного предшественника -> парный Jaccard;
#   - сборка из нескольких -> покрытие объединением (парный при этом низкий: у
#     seven-pairs-mixed максимальная пара всего 0.38, а покрытие 0.71).
# Калибровка по корпусу 114: медиана покрытия 0.46, медиана пары 0.14. Пороги ниже —
# это ~1.5× и ~3× от медианы, и на них лежат ровно те три брифа, которые аудит назвал
# пересъёмкой поимённо.
DUPLICATE_COVERAGE = 0.70      # доля лексики брифа, уже покрытая предшественниками
DUPLICATE_PAIRWISE = 0.45      # Jaccard с одним предшественником
DUPLICATE_WINDOW_DAYS = 30

_WORD = re.compile(r"[а-яёa-z]{4,}")


def _lexis(text):
    return set(_WORD.findall(str(text or "").lower()))


def duplicate_content(script, prior_scripts):
    """Сценарий пересобран из уже одобренных брифов той же формулы -> строка дефекта.

    prior_scripts — тексты предшественников (вызывающий отбирает по формуле и окну).
    Слова короче 4 букв отброшены: предлоги и союзы дают одинаковый фон любым двум
    текстам на русском и размывают сигнал.
    """
    new = _lexis(script)
    priors = [(_lexis(p), i) for i, p in enumerate(prior_scripts) if p]
    priors = [(s, i) for s, i in priors if s]
    if len(new) < 20 or not priors:   # слишком короткий текст — сигнал недостоверен
        return None

    union = set().union(*[s for s, _ in priors])
    coverage = len(new & union) / len(new)
    best = max(len(new & s) / len(new | s) for s, _ in priors)

    if best >= DUPLICATE_PAIRWISE:
        return (f"сценарий повторяет уже одобренный бриф этой формулы: совпадение "
                f"{best:.0%} лексики (норма — до {DUPLICATE_PAIRWISE:.0%})")
    if coverage >= DUPLICATE_COVERAGE:
        return (f"сценарий пересобран из предыдущих брифов формулы: {coverage:.0%} "
                f"лексики уже была в них (норма — до {DUPLICATE_COVERAGE:.0%}); "
                f"ротация tested_variable не выполнена")
    return None


def craft_defects(brief, hook_timing_seconds=None, prior_scripts=()):
    """Все проверки ремесла одним вызовом. brief — dict-подобная строка брифа.

    Возврат: список строк дефектов (пустой -> зелёно). Порядок — по тяжести: сначала
    то, из-за чего сценарий нельзя снять, потом то, из-за чего он развалится в кадре.
    """
    hook = brief.get("hook")
    script = brief.get("script_text") or brief.get("script")
    visual = brief.get("visual_direction")
    caption = brief.get("caption")
    cta = brief.get("cta")

    defects = []
    for check in (unfilled_placeholders(hook, script, visual, caption, cta),
                  self_contradiction(script, visual, caption, cta),
                  duplicate_content(script, prior_scripts),
                  hook_is_stage_direction(hook),
                  hook_overrun(hook, hook_timing_seconds)):
        if check:
            defects.append(check)
    defects.extend(segment_overruns(script))
    return defects
