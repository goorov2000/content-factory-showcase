// Подтверждение платных запусков (решение владельца 2026-07-28, элементы 15 и 17е).
//
// Правило одно на все платные кнопки: «▶ Полный цикл» на карточке «Конвейер», ▶ на
// каждой строке ленты и ▶ ритуалов в лаборатории. Клик по ним немедленно тратит
// деньги на вызовы агентов, а цикл и так идёт сам в 07:30 (cf-cycle.timer) —
// случайный клик не должен стоить прогона. Стрелка «→ открыть» ничего не запускает
// и подтверждения не спрашивает.
//
// Обработчик висит НА ДОКУМЕНТЕ (делегирование), а не на самих формах: лента
// подменяется htmx раз в 2 секунды, и слушатель, повешенный на кнопку, исчезал бы
// вместе с ней при первом же свопе. По той же причине htmx-кнопки пользуются
// штатным hx-confirm — он не добавляет разметки и не трогает id, а на id завязан
// возврат фокуса клавиатуры после подмены (partials/stages.html).
//
// window.confirm выбран намеренно: он доступен с клавиатуры и озвучивается
// скринридером «из коробки», без своей ловушки фокуса и своей роли ARIA.
(function () {
  document.addEventListener('submit', function (evt) {
    var form = evt.target;
    if (!form || typeof form.getAttribute !== 'function') return;
    var question = form.getAttribute('data-confirm');
    if (!question) return;
    if (!window.confirm(question)) {
      evt.preventDefault();
      evt.stopPropagation();
    }
  });
})();
