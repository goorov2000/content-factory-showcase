def cycle_summary(formulas, pending, config=None):
    """Чем закончился ночной прогон.

    Главное в сообщении — сколько сценариев ждут решения владельца: это его
    единственная работа в заводе. До правки эта цифра была хвостовым огрызком
    строки «Контент-завод» завершён · формул 0 · брифов ждут ревью 9».
    """
    link = dashboard_link(config, "/briefs")
    if pending:
        word = plural_ru(pending, "сценарий", "сценария", "сценариев")
        verb = plural_ru(pending, "ждёт", "ждут", "ждут")
        head = f"📋 {pending} {word} {verb} твоего решения"
        call = link or "Открой пульт, раздел «Сценарии»."
    else:
        head = "✅ Завод отработал за ночь."
        if pending == 0:
            head += " Новых сценариев на одобрение нет."
        call = ""
    extra = ""
    if formulas:
        word = plural_ru(formulas, "рецепт", "рецепта", "рецептов")
        extra = f"Заодно добавилось {formulas} {word} для новых роликов."
    return _blocks(head, call, extra)


def cycle_degraded(stage_labels, config=None):
    """Часть этапов не отработала, но цикл доехал до конца."""
    names = ", ".join(str(s).strip("«»") for s in stage_labels)
    one = len(list(stage_labels)) == 1
    return _blocks(
        "🟡 Сегодня завод работал не полностью",
        f"Не {'отработал' if one else 'отработали'} этап"
        f"{'' if one else 'ы'}: {names}. Остальное прошло нормально, "
        f"сценарии делались.",
        "Если рядом пришло красное сообщение — причина в нём.",
    )
