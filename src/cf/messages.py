DEFAULT_MEANING = "Внешний сервис ответил ошибкой, разбирать надо руками."
DEFAULT_ACTION = ("открой пульт, раздел «Отчёты этапов» — там лежит полный "
                  "текст ошибки.")


def explain(error):
    """Техническая ошибка → (что это значит, что делать) по-человечески."""
    low = str(error or "").lower()
    for markers, meaning, action in CAUSES:
        if all(m in low for m in markers):
            return meaning, action
    return DEFAULT_MEANING, DEFAULT_ACTION


def dashboard_link(config=None, path=""):
    """Адрес страницы пульта — или пустая строка, если адрес не настроен.

    Берётся из `dashboard.public_origin`. До 2026-08-09 этот ключ в конфиге
    был, а в текстах уведомлений не использовался ни разу: человеку сообщали
    «брифов ждут ревью 9» и оставляли самому вспоминать домен.
    """
    origin = str(((config or {}).get("dashboard") or {}).get(
        "public_origin", "") or "").strip()
    return origin.rstrip("/") + path if origin else ""


def _blocks(*parts):
    """Склеить непустые блоки через пустую строку (абзацы читаются с телефона)."""
    return "\n\n".join(p.strip() for p in parts if p and str(p).strip())


def _stage_name(stage):
    return STAGE_NAMES.get(stage, f"Сбор «{stage}»")


def _day_suffix(day):
    """«— 6-й день» для держащейся проблемы; в первый день — ничего.

    Повтор без счётчика неотличим от нового сбоя: владелец пятое утро подряд
    читал одинаковый текст и не мог понять, это всё та же авария или новая.
    """
    return f" — {day}-й день" if day and day > 1 else ""


def _source_name(marker):
    """Маркер грамматики source_query -> имя для человека.

    Сборщики отдают факты про источники маркерами ('hashtag:#x' / 'query:q') —
    это их каноническое имя во всей системе (атрибуция строк, proposals).
    Служебный префикс человеку не адресован: тег остаётся '#x', поисковый
    запрос берётся в кавычки.
    """
    m = str(marker or "").strip()
    if m.startswith("hashtag:"):
        return m.split(":", 1)[1]
    if m.startswith("query:"):
        return "«" + m.split(":", 1)[1] + "»"
    return m


def collect_sources_block(summary, config=None):
    """Что прогон сделал с источниками (тикет 06 плана 2026-08-10-apify-costs).

    Обещание §5 спеки бота: владелец видит, что завод пробует новое, а не
    только пережёвывает старое, — сколько пробных источников проверено этим
    прогоном, что предложено в постоянные (лежит предложение), что снято с
    проверки за бесплодие. Факты берутся из summary["exploration"], который
    возвращают сборщики; прогон без exploration-активности блока не получает
    вообще — ни заголовка, ни нулей.
    """
    expl = (summary or {}).get("exploration") or {}

    def names(key):
        return [_source_name(m) for m in (expl.get(key) or [])
                if str(m or "").strip()]

    explored, promoted, retired = (names(k) for k in
                                   ("explored", "promoted", "retired"))
    parts = []
    if explored:
        word = plural_ru(len(explored), "пробный источник",
                         "пробных источника", "пробных источников")
        parts.append(f"Завод заодно проверил {len(explored)} {word}: "
                     + ", ".join(explored) + ".")
    if promoted:
        one = len(promoted) == 1
        parts.append(
            ", ".join(promoted)
            + f" {'принёс' if one else 'принесли'} ролики не хуже постоянных "
              f"источников — готово предложение добавить "
              f"{'его' if one else 'их'} насовсем. Решение за тобой: "
            + (dashboard_link(config, "/sources")
               or "раздел «Источники» в пульте"))
    if retired:
        one = len(retired) == 1
        parts.append(
            ", ".join(retired)
            + f" больше не {'проверяется' if one else 'проверяются'}: "
              f"за несколько проверок {'он' if one else 'они'} почти ничего "
              f"не {'принёс' if one else 'принесли'}.")
    return "🌱 " + "\n\n".join(parts) if parts else ""


def collect_alert(stage, summary, config=None, day=1):
    """Сборщик упал или не привёз строк — что показать владельцу."""
    summary = summary or {}
    name = _stage_name(stage)
    if str(summary.get("status") or "") == "insufficient_data":
        return _blocks(
            f"🟡 {name}: сегодня ничего нового{_day_suffix(day)}",
            "Источники ответили, но новых роликов среди них не нашлось. "
            "Это не поломка — так бывает, когда авторы давно не публиковались.",
            "Если повторится несколько дней подряд, стоит обновить список "
            "источников: " + (dashboard_link(config, "/sources") or "раздел "
                              "«Источники» в пульте"),
            collect_sources_block(summary, config),
        )
    meaning, action = explain(summary.get("error"))
    return _blocks(f"🔴 {name} не работает{_day_suffix(day)}", meaning,
                   f"Что делать: {action}", IMPACTS.get(stage, ""),
                   collect_sources_block(summary, config))


def collect_crash_alert(stage, exc, config=None, day=1):
    """Сборщик не смог даже стартовать (ключи, таблица, сеть)."""
    meaning, action = explain(f"{type(exc).__name__}: {exc}")
    return _blocks(f"🔴 {_stage_name(stage)} не запустился{_day_suffix(day)}",
                   meaning, f"Что делать: {action}", IMPACTS.get(stage, ""))


def collect_recovered(stage, config=None, summary=None):
    """Починилось. Закрыть тему обязательно — иначе тревога висит открытой.

    summary — сводка ПОЧИНИВШЕГОСЯ прогона: это единственное сообщение
    успешного сбора, и факты про источники (тикет 06) едут в нём, когда есть.
    """
    return _blocks(f"✅ {_stage_name(stage)} снова работает.",
                   collect_sources_block(summary, config))


def unit_failed(unit, config=None, day=1):
    """Служба на сервере упала — про это раньше не узнавал никто.

    Зовётся из OnFailure= самого systemd, отдельным процессом: сообщение уходит,
    даже когда лежит сам пульт (прежде отправитель жил внутри него).
    """
    name = UNIT_NAMES.get(unit, unit)
    return _blocks(
        f"🔴 На сервере не отработало: {name}{_day_suffix(day)}",
        SERVICE_IMPACTS.get(unit, "Что это ломает — видно в пульте."),
        "Что делать: скажи мне, я посмотрю журнал и разберусь.",
    )


def cycle_missing(hours=None, config=None, day=1):
    """Завод не отработал утром, и об этом не сказал никто (сторож).

    Дыра, ради которой сторож и делался: тишина в чате означала одновременно
    «всё хорошо» и «завод умер», и различить их было нельзя.
    """
    if hours:
        detail = (f"Последний прогон закончился больше {int(hours)} часов "
                  f"назад — значит утренний цикл не запустился или оборвался "
                  f"в самом начале.")
    else:
        detail = ("Не удалось понять, когда завод отрабатывал в последний "
                  "раз: отметка о прогоне не читается.")
    return _blocks(
        f"🔴 Завод не отработал{_day_suffix(day)}", detail,
        "Что делать: скажи мне, я посмотрю, что со службами на сервере.",
        dashboard_link(config, "/runs"),
    )


def formulas_paused(paused, config=None):
    """Машина сняла рецепт(ы) с производства — страховка сработала.

    Не авария: так и задумано, плохой рецепт перестаёт давать сценарии. Но это
    производственное решение, принятое без человека, и он вправе о нём знать.
    """
    items = list(paused)
    word = plural_ru(len(items), "рецепт", "рецепта", "рецептов")
    head = (f"🟡 Снят с производства {word}: «{items[0][0]}»" if len(items) == 1
            else f"🟡 С производства снято {len(items)} {word}")
    if len(items) > 1:
        body = "\n".join(f"• «{name}» — {_human_reason(reason)}"
                         for name, reason in items)
    else:
        first = _human_reason(items[0][1])
        body = first[:1].upper() + first[1:] + "."
    return _blocks(
        head, body,
        "Это страховка: рецепт перестал давать годные сценарии, и завод больше "
        "не делает по нему новых. Остальные рецепты работают как обычно.",
        "Срочного ничего — но если считаешь решение неверным, скажи мне.",
        dashboard_link(config, "/lab"),
    )


