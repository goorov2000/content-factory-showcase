# Причины гвардии пишутся для Run Log и несут внутренний жаргон («reject»).
# Формулировку в журнале не трогаем — переводим здесь, на выходе к человеку.
_REASON_FIXES = (
    (re.compile(r"авто-пауза:\s*"), ""),
    (re.compile(r"(\d+)\s+reject\s+из\s+последних\s+(\d+)"),
     r"\1 из последних \2 сценариев забракованы"),
    (re.compile(r"\breject\b"), "отказ"),
)


def _human_reason(reason):
    text = str(reason or "").strip()
    for pattern, replacement in _REASON_FIXES:
        text = pattern.sub(replacement, text)
    return text

