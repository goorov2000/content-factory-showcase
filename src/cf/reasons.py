"""Единый словарь кодов причин reject/revise (P5.12).

Свободный текст причины никогда не повторяется дословно, поэтому rejection-history
не мог накапливать повторы, а evidence-петля Prompt Optimizer была мертва по
построению. Код из фиксированного enum — стабильный ключ группировки: повторы
копятся, и оптимизатор видит «N случаев reference_mismatch».

Хранение: код кладётся СТРУКТУРНЫМ ПРЕФИКСОМ в уже существующую колонку
rejection_reason листа CF Creative Briefs — '[reference_mismatch]' (+ необязательная
человекочитаемая деталь). Новую колонку заводить сознательно НЕ стали:
update_row_fields падает UnknownFieldsError на поле вне заголовков живого листа, то
есть запись reject ломалась бы целиком до операторской миграции. Префикс в
существующей колонке работает сразу и деградирует мягко — старые записи без префикса
группируются по своему тексту, отчёт не ломается.

Это единственный источник кодов: CLI (--reason-code), rejection-history, дропдаун
дашборда и промпт brief-reviewer опираются на REASON_CODES здесь.
"""

import re

# code -> русский UI-лейбл. Порядок = порядок в дропдауне дашборда.
REASON_CODES = {
    "reference_mismatch": "Референс не соответствует скрипту",
    "female_reference": "Женский референс в мужском брифе",
    "prohibition_violation": "Нарушение prohibitions формулы",
    "weak_hook": "Слабый хук",
    "not_producible": "Невозможно снять одним креатором",
    # Три кода добавлены 2026-08-04 по аудиту 114 сценариев: их дефекты копились
    # молча, потому что все три попадали в «Другое» и не группировались, а Prompt
    # Optimizer видит только повторы ПО КОДУ.
    "derivative_script": "Сценарий повторяет уже одобренный",
    "self_contradiction": "Скрипт противоречит капшену",
    "unfilled_placeholder": "Незаполненные подстановки в тексте",
    "other": "Другое",
}

# '[code]' в начале строки. Скобки делают код однозначно отличимым от старого
# свободного текста (который скобками не начинался). Регистр допускаем любой:
# оператор мог поправить ячейку руками ('[WEAK_HOOK]') — тот же класс, что P1.10.
_PREFIX_RE = re.compile(r"^\s*\[([a-zA-Z_]+)\]")


def is_reason_code(code):
    """Известен ли код (входит в enum)."""
    return code in REASON_CODES


def format_reason(code, detail=""):
    """Значение колонки rejection_reason: '[code]' + необязательная деталь.

    Код — в квадратных скобках (ключ группировки rejection-history), деталь идёт
    человекочитаемым хвостом и на группировку НЕ влияет. Невалидный код —
    программная ошибка вызывающего (записали бы '[bogus]', который parse не узнает),
    поэтому падаем ValueError, а не пишем мусорный префикс."""
    if not is_reason_code(code):
        raise ValueError(f"неизвестный reason-code: {code!r}")
    base = f"[{code}]"
    detail = str(detail).strip()
    return f"{base} {detail}" if detail else base


def parse_reason_code(rejection_reason):
    """Извлечь известный код из значения rejection_reason.

    Канонический код (нижний регистр), если строка начинается с '[<известный код>]'
    в любом регистре; иначе None (старый свободный текст — группируется по самому
    тексту, отчёт не ломается)."""
    m = _PREFIX_RE.match(str(rejection_reason or ""))
    if m:
        code = m.group(1).lower()
        if code in REASON_CODES:
            return code
    return None
